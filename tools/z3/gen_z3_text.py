#!/usr/bin/env python3
"""Writes core/z3gen/z3_text_gen.{h,c}: the text data alttpr's ROM writer and Randomizer::setTexts/HintService use.

Input is the JSON the PHP oracle dumps (`tools/z3/oracle/oracle.sh textdata textdata.json`), so every value is what
alttpr itself computes: the dialog table after Rom's Text::removeUnwanted (already encoded, in table order), the
string pools of strings/*.txt as Randomizer::getTextArray splits them, the hint names exactly as __('hint.item.X') and
__('hint.location.X') return them (a string, an array to draw from, or the key itself when missing), and the texts
the special locations' writeItem sets for every item (Pedestal credits and tablet, Ether, Bombos, Uncle, Zora, Witch,
Sick Kid, Flute Spot).

    tools/z3/gen_z3_text.py textdata.json
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_H = ROOT / "core/z3gen/z3_text_gen.h"
OUT_C = ROOT / "core/z3gen/z3_text_gen.c"
WORLD_C = ROOT / "core/z3gen/z3_world_gen.c"

POOLS = ["uncle", "tavern_man", "blind", "ganon_1", "ganon_phase_3_no_silvers", "triforce", "hint"]
LOCTEXT = [("Master Sword Pedestal", "getItemCreditsText", "PEDESTAL_CREDITS"),
           ("Master Sword Pedestal", "getItemPedestalText", "PEDESTAL"),
           ("Ether Tablet", "getItemText", "ETHER"), ("Bombos Tablet", "getItemText", "BOMBOS"),
           ("Link's Uncle", "getItemCreditsText", "UNCLE_CREDITS"), ("King Zora", "getItemCreditsText", "ZORA_CREDITS"),
           ("Potion Shop", "getItemCreditsText", "WITCH_CREDITS"), ("Sick Kid", "getItemCreditsText", "KID_CREDITS"),
           ("Flute Spot", "getItemCreditsText", "GROVE_CREDITS")]


def cstr(s):
    """A C string literal for s in UTF-8; octal escapes never run into the next character."""
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def wrap(items, indent="    ", width=116):
    lines, cur = [], indent
    for it in items:
        piece = it + ", "
        if len(cur) + len(piece) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += piece
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def main():
    data = json.loads(Path(sys.argv[1]).read_text())
    world = WORLD_C.read_text()
    items = re.search(r"Z3_ITEMS\[Z3_ITEM_COUNT\] = \{(.*?)\n\};", world, re.S).group(1)
    item_names = re.findall(r'\{ "([^"]+)", Z3_IC_', items)
    locs = re.search(r"Z3_LOCS\[Z3_LOC_COUNT\] = \{(.*?)\n\};", world, re.S).group(1)
    loc_names = [n.replace('\\"', '"') for n in re.findall(r'\{ "((?:[^"\\]|\\.)*)", "', locs)]

    text = data["text"]
    h = ["/* Generated by tools/z3/gen_z3_text.py from alttp_php_randomizer (sporchia, MIT). Do not edit. */",
         "#ifndef Z3_TEXT_GEN_H", "#define Z3_TEXT_GEN_H", "", "#include <stdint.h>", '#include "z3_world_gen.h"', "",
         "/* Text::en() keys in table order (Text::getByteArray concatenates them in this order). */", "enum {"]
    for i, (k, _) in enumerate(text):
        h.append(f"    Z3_TXT_{k} = {i},")
    h += [f"    Z3_TXT_COUNT = {len(text)},", "};", "",
          "/* Each entry's bytes after Rom's removeUnwanted(): Z3_TEXT_DATA[Z3_TEXT_OFF[k] .. Z3_TEXT_OFF[k + 1]). */",
          "extern const uint8_t Z3_TEXT_DATA[];", "extern const uint16_t Z3_TEXT_OFF[Z3_TXT_COUNT + 1];", "",
          "/* strings/<pool>.txt as Randomizer::getTextArray reads them (array_filter'ed, in file order). */",
          "typedef struct { const char *const *s; int n; } Z3StrList;", "enum {"]
    for i, p in enumerate(POOLS):
        h.append(f"    Z3_STRS_{p.upper()} = {i},")
    h += [f"    Z3_STRS_COUNT = {len(POOLS)},", "};", "extern const Z3StrList Z3_STRS[Z3_STRS_COUNT];", "",
          "/* __('hint.item.<raw name>') and __('hint.location.<name>'): is_array means fy_shuffle and take the first;",
          "   a missing key comes back as the key itself, as Laravel's translator does. */",
          "typedef struct { const char *const *s; uint8_t n, is_array; } Z3HintName;",
          "extern const Z3HintName Z3_HINT_ITEM[Z3_ITEM_COUNT];", "extern const Z3HintName Z3_HINT_LOC[Z3_LOC_COUNT];", "",
          "/* What the special locations' writeItem sets, per item (by its target; NULL for the aliases). */", "enum {"]
    for i, (_, _, e) in enumerate(LOCTEXT):
        h.append(f"    Z3_LT_{e} = {i},")
    h += [f"    Z3_LT_COUNT = {len(LOCTEXT)},", "};", "extern const char *const Z3_LOC_TEXT[Z3_LT_COUNT][Z3_ITEM_COUNT];", "",
          "#endif", ""]

    c = ["/* Generated by tools/z3/gen_z3_text.py from alttp_php_randomizer (sporchia, MIT). Do not edit. */",
         "#include <stddef.h>", '#include "z3_text_gen.h"', ""]
    blob, offs = [], [0]
    for _, b in text:
        blob += b
        offs.append(len(blob))
    c.append("const uint8_t Z3_TEXT_DATA[] = {")
    c.append(wrap(["0x%02X" % b for b in blob]))
    c += ["};", "", "const uint16_t Z3_TEXT_OFF[Z3_TXT_COUNT + 1] = {", wrap([str(o) for o in offs]), "};", ""]

    for p in POOLS:
        c.append(f"static const char *const STRS_{p.upper()}[] = {{")
        c += ["    " + cstr(s) + "," for s in data["strings"][p]]
        c += ["};", ""]
    c.append("const Z3StrList Z3_STRS[Z3_STRS_COUNT] = {")
    c += [f"    {{ STRS_{p.upper()}, {len(data['strings'][p])} }}," for p in POOLS]
    c += ["};", ""]

    def names(table, keys, prefix, label):
        rows = []
        for i, k in enumerate(keys):
            v = table.get(k, f"hint.{label}.{k}")
            vals = v if isinstance(v, list) else [v]
            c.append(f"static const char *const {prefix}{i}[] = {{ " + ", ".join(cstr(x) for x in vals) + " };")
            rows.append(f"    {{ {prefix}{i}, {len(vals)}, {1 if isinstance(v, list) else 0} }},")
        return rows

    rows = names(data["hint_item"], item_names, "HI", "item")
    c += ["", "const Z3HintName Z3_HINT_ITEM[Z3_ITEM_COUNT] = {"] + rows + ["};", ""]
    rows = names(data["hint_location"], loc_names, "HL", "location")
    c += ["", "const Z3HintName Z3_HINT_LOC[Z3_LOC_COUNT] = {"] + rows + ["};", ""]

    pool, index = [], {}
    tables = []
    for loc, method, _ in LOCTEXT:
        lt = next(x for x in data["loctext"] if x["location"] == loc and x["method"] == method)
        row = []
        for name in item_names:
            s = lt["texts"].get(name)
            if s is None:
                row.append("NULL")
                continue
            if s not in index:
                index[s] = len(pool)
                pool.append(s)
            row.append(f"LT{index[s]}")
        tables.append(row)
    for i, s in enumerate(pool):
        c.append(f"static const char LT{i}[] = {cstr(s)};")
    c += ["", "const char *const Z3_LOC_TEXT[Z3_LT_COUNT][Z3_ITEM_COUNT] = {"]
    for row in tables:
        c += ["    {", wrap(row, "        "), "    },"]
    c += ["};", ""]

    OUT_H.write_text("\n".join(h))
    OUT_C.write_text("\n".join(c))
    print(f"{len(text)} dialog entries ({len(blob)} bytes), {len(pool)} location texts -> {OUT_C.name}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes core/z3gen/z3_enemizer_gen.{h,c}: the Enemizer's base patch (enemizerBasePatch.json) and the PC addresses of
the symbols its boss shuffle writes to (exported_symbols.txt), as shipped in alttpr's z3/enemizer_linux 6.1.0.180
(the alttpr-com branch of cassidoxa/Enimizer, a fork of Zarby89/Enemizer, MIT). Take both files from the oracle image:
  docker run --rm --entrypoint cat smz3u-z3oracle:219fcafd /alttpr/vendor/z3/enemizer_linux/enemizerBasePatch.json
  docker run --rm --entrypoint cat smz3u-z3oracle:219fcafd /alttpr/vendor/z3/enemizer_linux/exported_symbols.txt
Usage: gen_z3_enemizer.py <enemizerBasePatch.json> <exported_symbols.txt>"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "core/z3gen/z3_enemizer_gen"
SYMBOLS = ["enemizer_info_table", "EnemizerFlags", "room_header_table", "modified_room_object_table",
           "sprite_bush_spawn_item_table"]

patch_raw = Path(sys.argv[1]).read_bytes()
sym_raw = Path(sys.argv[2]).read_bytes()
patch = json.loads(patch_raw)
syms = {}
for line in sym_raw.decode().splitlines():
    name, sep, addr = line.partition(" = $")
    if sep:
        a = int(addr, 16)
        syms[name] = ((a & 0x7F0000) >> 1) | (a & 0x7FFF)   # Utilities.SnesToPCAddress (2 MB build)

# Records in file order (Patch.PatchRom applies them so): 3-byte address, 2-byte length, little endian, then the data.
blob = bytearray()
for p in patch:
    a, d = p["address"], p["patchData"]
    blob += bytes([a & 0xFF, (a >> 8) & 0xFF, a >> 16, len(d) & 0xFF, len(d) >> 8]) + bytes(d)

note = (f"/* Generated by tools/z3/gen_z3_enemizer.py from the Enemizer's enemizerBasePatch.json (MD5 "
        f"{hashlib.md5(patch_raw).hexdigest()})\n   and exported_symbols.txt (MD5 {hashlib.md5(sym_raw).hexdigest()}). "
        "Enemizer: Copyright (c) 2023 Zarby89, MIT licence. Do not edit. */")
h = [note, "#ifndef Z3_ENEMIZER_GEN_H", "#define Z3_ENEMIZER_GEN_H", "", "#include <stddef.h>", "#include <stdint.h>", ""]
h += [f"#define Z3_EN_{n.upper()} 0x{syms[n]:06X}" for n in SYMBOLS]
h += ["", f"#define Z3_EN_BASE_PATCH_RECORDS {len(patch)}",
      "extern const uint8_t Z3_EN_BASE_PATCH[];", "extern const size_t Z3_EN_BASE_PATCH_LEN;", "", "#endif", ""]
c = [note, '#include "z3_enemizer_gen.h"', "", "const uint8_t Z3_EN_BASE_PATCH[] = {"]
for i in range(0, len(blob), 16):
    c.append("    " + " ".join(f"0x{b:02X}," for b in blob[i:i + 16]))
c += ["};", f"const size_t Z3_EN_BASE_PATCH_LEN = {len(blob)};", ""]
OUT.with_suffix(".h").write_text("\n".join(h))
OUT.with_suffix(".c").write_text("\n".join(c))
print(f"{len(patch)} records, {len(blob)} bytes -> {OUT}.{{h,c}}")

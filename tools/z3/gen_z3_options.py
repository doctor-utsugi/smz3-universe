#!/usr/bin/env python3
"""Writes core/z3gen/z3_options_gen.c: the Z3 option table in alttpr's own keys, values and labels
(config/alttp.php randomizer.item), cut to the first release (docs/STANDALONE.md, Community options > Z3), with the
defaults of the 'default' preset. Tournament and the cosmetics are not in that config: they come from
RandomizerController (tournament) and Rom::setHeartBeepSpeed/setMenuSpeed/setQuickSwap."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CFG = (ROOT / "vendor/alttp_php_randomizer/config/alttp.php").read_text()
OUT = ROOT / "core/z3gen/z3_options_gen.c"

# key -> (description, values kept for the first release; None keeps them all)
RELEASE = [
    ("world_state", "World State", ["standard", "open"]),
    ("goals", "Goal", ["ganon", "fast_ganon", "dungeons", "pedestal"]),
    ("tower_open", "Open Tower", None),
    ("ganon_open", "Ganon Vulnerable", None),
    ("dungeon_items", "Dungeon Items", None),
    ("accessibility", "Accessibility", None),
    ("item_placement", "Item Placement", None),
    ("weapons", "Swords", None),
    ("item_pool", "Item Pool", ["normal", "hard", "expert"]),
    ("item_functionality", "Item Functionality", None),
    ("hints", "Hints", None),
]
PRESET_KEY = {"goals": "goal"}
EXTRA = [   # not in config/alttp.php
    ("tournament", "Tournament (no spoiler)", "checkbox", [], "false"),
    ("heart_beep", "Heart Beep", "dropdown", [("off", "Off"), ("double", "Double"), ("normal", "Normal"),
                                              ("half", "Half"), ("quarter", "Quarter")], "normal"),
    ("menu_speed", "Menu Speed", "dropdown", [("slow", "Slow"), ("normal", "Normal"), ("fast", "Fast"),
                                              ("instant", "Instant")], "normal"),
    ("quickswap", "Item Quickswap", "checkbox", [], "true"),
]

item = CFG[CFG.index("'randomizer' => ["):]
preset = re.search(r"'default' => \[(.*?)\]", item, re.S).group(1)
DEFAULT = dict(re.findall(r"'(\w+)' => '([^']*)'", preset))
lists = item[item.index("'glitches_required' => ["):]

out = ["/* Generated by tools/z3/gen_z3_options.py from alttp_php_randomizer config/alttp.php. Do not edit. */",
       '#include "z3_generate.h"', ""]
rows = []
for key, desc, keep in RELEASE:
    body = re.search(r"^ {12}'" + key + r"' => \[(.*?)^ {12}\],", lists, re.S | re.M).group(1)
    vals = re.findall(r"'([^']+)' => '([^']*)'", body)
    if keep:
        vals = [v for v in vals if v[0] in keep]
    out.append(f"static const Z3OptValue z3_opt_{key}_values[] = {{")
    out += [f'    {{ "{k}", "{d}" }},' for k, d in vals]
    out.append("};")
    rows.append(f'    {{ "{key}", "{desc}", "dropdown", z3_opt_{key}_values, {len(vals)}, "{DEFAULT[PRESET_KEY.get(key, key)]}" }},')
for key, desc, typ, vals, dflt in EXTRA:
    if vals:
        out.append(f"static const Z3OptValue z3_opt_{key}_values[] = {{")
        out += [f'    {{ "{k}", "{d}" }},' for k, d in vals]
        out.append("};")
        rows.append(f'    {{ "{key}", "{desc}", "{typ}", z3_opt_{key}_values, {len(vals)}, "{dflt}" }},')
    else:
        rows.append(f'    {{ "{key}", "{desc}", "{typ}", 0, 0, "{dflt}" }},')
out += ["", "const Z3Option Z3_OPTIONS[] = {"] + rows + ["};", f"const int Z3_OPTION_COUNT = {len(rows)};", ""]
OUT.write_text("\n".join(out))
print(f"{len(rows)} options -> {OUT}")

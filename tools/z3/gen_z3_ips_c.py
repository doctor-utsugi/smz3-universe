#!/usr/bin/env python3
"""Packs the A Link to the Past base patch (z3_base.ips) into a C array, so z3 generation needs no data files."""
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
out = ["/* Generated by tools/z3/gen_z3_ips_c.py from patches/z3_base.ips (KatDevsGames/z3randomizer, MIT). Do not edit. */",
       "#include <stddef.h>", "#include <stdint.h>", "", "const uint8_t Z3_BASE_IPS[] = {"]
for i in range(0, len(data), 24):
    out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
out += ["};", "const size_t Z3_BASE_IPS_LEN = sizeof Z3_BASE_IPS;", ""]
open(dst, "w").write("\n".join(out))
print(f"{len(data)} bytes -> {dst}")

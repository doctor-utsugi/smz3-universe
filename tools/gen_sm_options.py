#!/usr/bin/env python3
"""Reads the option list of tewtal's Randomizer.SuperMetroid (RandomizerOptions.List and the enum attributes in
Config.cs) into core/smgen/sm_options_gen.c (types in sm_generate.h): the same keys, descriptions, values and defaults as `gen-cli-sm schema`.
Game mode and players (multiworld) and the seed field are left out: the port is single world and takes the seed apart."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SM = ROOT / "vendor/tewtal-SMZ3Randomizer/Randomizer.SuperMetroid"
cfg = (SM / "Config.cs").read_text(encoding="utf-8-sig")
opts = (SM / "RandomizerOptions.cs").read_text(encoding="utf-8-sig")

enums = {}
for m in re.finditer(r"\[DefaultValue\((\w+)\)\]\s*enum (\w+) \{(.*?)\}", cfg, re.S):
    default, name, body = m.groups()
    vals = re.findall(r'(?:\[Description\("([^"]*)"\)\]\s*)?(\w+),', body)
    enums[name] = (default, [(v, d or v) for d, v in vals])

rows = []
lst = re.search(r"List<IRandomizerOption> List \{ get; \} = new List<IRandomizerOption> \{(.*?)\};", opts, re.S).group(1)
for m in re.finditer(r'CreateEnumOption<(\w+)>\("([^"]+)"\)|CreateBoolOption\("(\w+)", "([^"]+)", (true|false)\)', lst):
    if m.group(1):
        if m.group(1) == "GameMode":
            continue
        default, vals = enums[m.group(1)]
        rows.append((m.group(1).lower(), m.group(2), "dropdown", vals, default.lower(), m.group(1)))
    else:
        rows.append((m.group(3).lower(), m.group(4), "checkbox", [], m.group(5), None))

out = ["/* Generated by tools/gen_sm_options.py from tewtal's Randomizer.SuperMetroid options. Do not edit. */",
       '#include "sm_generate.h"', ""]
for key, desc, typ, vals, default, enum in rows:
    if vals:
        out.append(f"static const SmOptValue sm_opt_{key}_values[] = {{")
        out += [f'    {{ "{v.lower()}", "{d}" }},' for v, d in vals]
        out.append("};")
out.append("\nconst SmOption SM_OPTIONS[] = {")
for key, desc, typ, vals, default, enum in rows:
    v = f"sm_opt_{key}_values, {len(vals)}" if vals else "0, 0"
    out.append(f'    {{ "{key}", "{desc}", "{typ}", {v}, "{default}" }},')
out += ["};", f"const int SM_OPTION_COUNT = {len(rows)};", ""]
(ROOT / "core/smgen/sm_options_gen.c").write_text("\n".join(out))
print(f"{len(rows)} options")

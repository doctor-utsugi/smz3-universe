#!/usr/bin/env python3
"""Copies the "Save the animals" IPS patches out of tewtal's Randomizer.SuperMetroid/Patch.cs into
core/smgen/sm_animals_data.h, in the C# dictionary order (Patch.WriteAnimalSurprise picks one by index)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "vendor/tewtal-SMZ3Randomizer/Randomizer.SuperMetroid/Patch.cs").read_text(encoding="utf-8-sig")
block = re.search(r"animalPatches = new Dictionary<string, byte\[\]> \{(.*?)\n        \};", src, re.S).group(1)
entries = re.findall(r'\["([^"]+)"\] = new byte ?\[\] \{(.*?)\}', block, re.S)
out = ["/* Generated by tools/gen_sm_patchdata.py from tewtal's Randomizer.SuperMetroid/Patch.cs. Do not edit. */",
       "#ifndef SM_ANIMALS_DATA_H", "#define SM_ANIMALS_DATA_H", ""]
for i, (name, data) in enumerate(entries):
    b = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", data)]
    out.append(f"/* {name} */")
    out.append(f"static const uint8_t sm_animal_{i}[] = {{")
    for k in range(0, len(b), 16):
        out.append("    " + ", ".join(f"0x{x:02X}" for x in b[k:k + 16]) + ",")
    out.append("};")
out.append("\nstatic const struct { const char *name; const uint8_t *ips; size_t len; } SM_ANIMALS[] = {")
out += [f'    {{ "{n}", sm_animal_{i}, sizeof sm_animal_{i} }},' for i, (n, _) in enumerate(entries)]
out += ["};", f"#define SM_ANIMAL_COUNT {len(entries)}", "", "#endif", ""]
(ROOT / "core/smgen/sm_animals_data.h").write_text("\n".join(out))
print(f"{len(entries)} animal patches")

#!/usr/bin/env python3
"""Packs the menu music (assets/music/smz3_intro.mp3) into a C file for the PC binary: gen_pc_music.py <in.mp3> <out.c>"""
import sys
data = open(sys.argv[1], "rb").read()
rows = (",".join(str(b) for b in data[i:i + 64]) for i in range(0, len(data), 64))
out = ["/* Generated by tools/gen_pc_music.py. Do not edit. */", "const unsigned long PC_MENU_MUSIC_SIZE = %d;" % len(data),
       "const unsigned char PC_MENU_MUSIC[] = {", ",\n".join(rows), "};"]
open(sys.argv[2], "w").write("\n".join(out) + "\n")

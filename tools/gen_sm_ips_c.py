#!/usr/bin/env python3
"""Packs the Super Metroid base patch (sm_randomizer.ips) into a C array, so sm_generate needs no data files."""
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
out = ["/* Generated by tools/gen_sm_ips_c.py from patches/sm_randomizer.ips (tewtal/sm_randomizer_rom, MIT). Do not edit. */",
       "#include <stddef.h>", "#include <stdint.h>", "", "const uint8_t SM_BASE_IPS[] = {"]
for i in range(0, len(data), 24):
    out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
out += ["};", "const size_t SM_BASE_IPS_LEN = sizeof SM_BASE_IPS;", ""]
open(dst, "w").write("\n".join(out))
print(f"{len(data)} bytes -> {dst}")
